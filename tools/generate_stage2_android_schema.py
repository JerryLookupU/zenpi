#!/usr/bin/env python3
"""Generate Android wire enums from the reviewed Rust/Android test contract."""
import argparse
import hashlib
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
CONTRACT = Path("fuzz/remote_protocol/schema-contract.json")
OUTPUT = Path("android/app/src/main/java/zenpi/transport/RemoteSchema.kt")
FIELDS = ("read_operations", "write_operations", "execution_states", "error_codes")


def pairs(values):
    result = {}
    for key, value in values:
        if key in result:
            raise ValueError("Duplicate schema contract field")
        result[key] = value
    return result


def render(raw: bytes) -> bytes:
    if len(raw) > 65536:
        raise ValueError("Schema contract exceeds limit")
    value = json.loads(raw, object_pairs_hook=pairs)
    if not isinstance(value, dict) or set(value) != {"schema_version", "messages", *FIELDS}:
        raise ValueError("Invalid schema contract fields")
    version = value["schema_version"]
    if type(version) is not int or not 1 <= version <= 65535:
        raise ValueError("Invalid schema version")
    for field in FIELDS:
        entries = value[field]
        if (not isinstance(entries, list) or not 1 <= len(entries) <= 128
                or any(not isinstance(item, str) or not re.fullmatch(r"[a-z][a-z0-9_]{0,63}", item) for item in entries)
                or len(set(entries)) != len(entries)):
            raise ValueError(f"Invalid schema contract list: {field}")
    if set(value["read_operations"]) & set(value["write_operations"]):
        raise ValueError("Operation cannot be both read and write")
    messages = value["messages"]
    if not isinstance(messages, dict) or not 1 <= len(messages) <= 32:
        raise ValueError("Invalid schema messages")
    for name, message in messages.items():
        if (not re.fullmatch(r"[a-z][a-z0-9_]{0,63}", name) or not isinstance(message, dict)
                or set(message) != {"channel", "fields", "payload", "envelope"}
                or message["channel"] not in ("control", "event", "bulk")):
            raise ValueError("Invalid schema message")
        fields = message["fields"]
        if (not isinstance(fields, list) or not 1 <= len(fields) <= 16
                or any(not isinstance(field, str) or not re.fullmatch(r"[a-z][a-z0-9_]{0,63}", field) for field in fields)
                or len(set(fields)) != len(fields) or "type" not in fields
                or not isinstance(message["payload"], dict) or set(message["payload"]) != set(fields)
                or message["payload"]["type"] != name or not isinstance(message["envelope"], dict)
                or set(message["envelope"]) & {"schema_version", "channel", "payload"}):
            raise ValueError("Invalid schema message fields/fixture")
    lines = ["// Generated by tools/generate_stage2_android_schema.py; do not edit.",
             f"// Contract SHA-256: {hashlib.sha256(raw).hexdigest()}",
             "package zenpi.transport", "", "internal object RemoteSchema {",
             f"    const val VERSION = {version}"]
    for field, name in (("read_operations", "READ_OPERATIONS"), ("write_operations", "WRITE_OPERATIONS"),
                        ("execution_states", "EXECUTION_STATES"), ("error_codes", "ERROR_CODES")):
        lines.append(f"    val {name}: Set<String> = setOf(")
        lines.extend(f'        "{item}",' for item in value[field])
        lines.append("    )")
    lines.append("    val OPERATIONS: Set<String> = READ_OPERATIONS + WRITE_OPERATIONS")
    lines.append("    val MESSAGE_FIELDS: Map<String, Set<String>> = mapOf(")
    for name, message in messages.items():
        fields = ", ".join(json.dumps(field) for field in message["fields"])
        lines.append(f'        "{name}" to setOf({fields}),')
    lines.append("    )")
    lines.append("    val MESSAGE_CHANNELS: Map<String, String> = mapOf(")
    lines.extend(f'        "{name}" to "{message["channel"]}",' for name, message in messages.items())
    lines.extend(["    )", "}", ""])
    return "\n".join(lines).encode("ascii")


def generate(root: Path = ROOT, check: bool = False):
    source = root / CONTRACT
    target = root / OUTPUT
    if source.is_symlink() or not source.is_file() or target.is_symlink():
        raise ValueError("Schema source/output must be regular files")
    expected = render(source.read_bytes())
    if check:
        if not target.is_file() or target.read_bytes() != expected:
            raise ValueError("Android schema is stale; run python3 tools/generate_stage2_android_schema.py")
    else:
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(expected)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Refuse stale generated source without modifying it")
    args = parser.parse_args()
    try:
        generate(check=args.check)
    except (ValueError, OSError) as error:
        raise SystemExit(str(error)) from error
    print("Android schema current" if args.check else "Android schema generated")


if __name__ == "__main__":
    main()

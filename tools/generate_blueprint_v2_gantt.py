#!/usr/bin/env python3
"""Generate the read-only same-name Gantt projection of the v2 Blueprint.

`Docs/Zenpi_Execution_Blueprint_v2.md` does not end in `Blueprint`, so the
companion appends `_Gantt` to the full stem.  The projection carries no
mutable checkboxes; every stable ID appears exactly once in the monitoring
index.  The Blueprint records no trustworthy dates, so the Mermaid view shows
dependency order with relative one-unit bars and every item is listed as
unscheduled.  `--check` fails when the committed companion is stale.
"""

from __future__ import annotations

import argparse
import hashlib
import sys
from datetime import datetime, timezone
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from validate_blueprint_v2 import BlueprintError, parse_header, parse_items, validate  # noqa: E402


BLUEPRINT = Path("Docs/Zenpi_Execution_Blueprint_v2.md")
COMPANION = Path("Docs/Zenpi_Execution_Blueprint_v2_Gantt.md")
STATE_LABEL = {" ": "open", "_": "self-tested", "x": "accepted"}
STATE_TAG = {" ": "", "_": "active, ", "x": "done, "}
GENERATED_PREFIX = "generated_at: "


def render(text: str, generated_at: str) -> str:
    validate(text)
    header = parse_header(text)
    items = parse_items(text)
    by_id = {item["id"]: item for item in items}
    digest = hashlib.sha256(text.encode("utf-8")).hexdigest()
    layers = [layer.strip() for layer in header["layers"].split(",")]

    out = [
        "# Zenpi Execution Blueprint v2 — Gantt (generated, read-only)",
        "",
        "> Generated by `tools/generate_blueprint_v2_gantt.py`. Do not edit; the",
        "> authoritative checklist is the Blueprint itself.",
        "",
        "```yaml",
        f"source: {BLUEPRINT.as_posix()}",
        f"source_sha256: {digest}",
        f"blueprint_version: {header['blueprint_version']}",
        f"{GENERATED_PREFIX}{generated_at}",
        "```",
        "",
        "## Dependency-order view",
        "",
        "Bars are relative one-unit slots ordered by `Depends`; they are not dates.",
        "",
        "```mermaid",
        "gantt",
        "    dateFormat X",
        "    axisFormat %d",
    ]
    for layer in layers:
        layer_items = [item for item in items if item["layer"] == layer]
        if not layer_items:
            continue
        out.append(f"    section {layer}")
        for item in layer_items:
            title = "".join(" " if ch in ":#;`,；" else ch for ch in item["title"])[:40].strip()
            tag = STATE_TAG[item["state"]]
            node = item["id"].replace("-", "_")
            if item["depends"]:
                after = " ".join(dep.replace("-", "_") for dep in item["depends"])
                out.append(f"    {item['id']} {title} :{tag}{node}, after {after}, 1d")
            else:
                out.append(f"    {item['id']} {title} :{tag}{node}, 0, 1d")
    out += ["```", "", "## Monitoring index", ""]

    counts = {state: sum(1 for item in items if item["state"] == state) for state in STATE_LABEL}
    out.append(
        f"Counts: open {counts[' ']} · self-tested {counts['_']} · accepted {counts['x']} · total {len(items)}"
    )
    out += [
        "",
        "| ID | Layer | State | Ready | Depends | Claim | Est. LOC | Title |",
        "|---|---|---|---|---|---|---:|---|",
    ]
    for item in items:
        ready = item["state"] != "x" and all(by_id[dep]["state"] == "x" for dep in item["depends"])
        deps = ", ".join(item["depends"]) or "—"
        title = item["title"].replace("|", "\\|")
        out.append(
            f"| {item['id']} | {item['layer']} | {STATE_LABEL[item['state']]} | "
            f"{'yes' if ready else 'no'} | {deps} | — | {item['loc']} | {title} |"
        )
    out += [
        "",
        "## Unscheduled",
        "",
        "No item has a recorded start or due date; all "
        f"{len(items)} items are unscheduled. Claims are empty until the controller records them.",
        "",
    ]
    return "\n".join(out)


def strip_generated(text: str) -> str:
    return "\n".join(line for line in text.splitlines() if not line.startswith(GENERATED_PREFIX))


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if the companion is missing or stale")
    args = parser.parse_args(argv)
    try:
        text = BLUEPRINT.read_text(encoding="utf-8")
        now = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
        rendered = render(text, now)
    except (BlueprintError, OSError) as error:
        print(f"Gantt generation failed: {error}", file=sys.stderr)
        return 1
    if args.check:
        if not COMPANION.exists() or strip_generated(COMPANION.read_text(encoding="utf-8")) != strip_generated(rendered):
            print(f"{COMPANION} is missing or stale; rerun tools/generate_blueprint_v2_gantt.py", file=sys.stderr)
            return 1
        print(f"{COMPANION} is current")
        return 0
    tmp = COMPANION.with_suffix(".md.tmp")
    tmp.write_text(rendered, encoding="utf-8")
    tmp.replace(COMPANION)
    print(f"wrote {COMPANION}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
